def _write_command(package_root: Path, command: str) -> None:
    slug = v1.slug(command)
    (package_root / "doc_sources" / "man" / f"{slug}.txt").write_text(
        FAKE_MAN_TEMPLATE.format(command=command, upper=slug.upper())
    )
    (package_root / "syntax_specs" / f"{slug}.py").write_text(
        FAKE_SPEC_TEMPLATE.format(command=slug)
    )



