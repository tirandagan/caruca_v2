def _write_fake_package(root: Path) -> Path:
    package_dir = root / "fake_site_packages"
    for relative, source in FAKE_PACKAGE_FILES.items():
        path = package_dir / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)
    return package_dir


def _write_fake_venv(root: Path) -> None:
    venv_bin = root / "caruca" / ".venv" / "bin"
    venv_bin.mkdir(parents=True)

    python = venv_bin / "python"
    python.write_text(
        f'#!/bin/sh\nPYTHONPATH="{root / "fake_site_packages"}" exec "{sys.executable}" "$@"\n'
    )
    python.chmod(0o755)

    annotation_file = root / "fake_v1_annotation.json"
    annotation_file.write_text(json.dumps(FAKE_V1_ANNOTATION, indent=1) + "\n")

    caruca = venv_bin / "caruca"
    echoes = "\n".join(f'echo "{line}"' for line in FAKE_CARUCA_INVOCATIONS)
    # The hint deliberately disagrees with the line count, as v1's own does.
    caruca.write_text(
        FAKE_CARUCA_SCRIPT.format(hint=99, echoes=echoes, annotation_file=annotation_file)
    )
    caruca.chmod(0o755)

@pytest.fixture
def fake_v1_root(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A minimal stand-in for the v1 checkout, pointed at by CARUCA_V1_ROOT.

    Its `.venv/bin/python` is a shell wrapper around the interpreter running the tests,
    with a miniature `caruca` package on the path. The subprocess boundary is therefore
    genuinely exercised — the same code path production uses — without needing the real,
    private v1 checkout to be present.
    """
    root = tmp_path / "caruca_v1"
    package_root = root / "caruca" / "src" / "caruca"
    (package_root / "doc_sources" / "man").mkdir(parents=True)
    (package_root / "syntax_specs").mkdir(parents=True)
    (package_root / "data").mkdir(parents=True)

    for command in (*v1.EXEMPLAR_COMMANDS, "mkdir", "git commit"):
        _write_command(package_root, command)

    _write_fake_package(root)
    _write_fake_venv(root)

    outputs = root / "caruca" / "outputs"
    outputs.mkdir(parents=True)
    (outputs / "mkdir.json").write_text(json.dumps(FAKE_TRACES, indent=1) + "\n")

    ground_truth = root / "benchmarks" / "annotations" / "pash"
    ground_truth.mkdir(parents=True)
    (ground_truth / "mkdir.json").write_text(
        json.dumps(FAKE_GROUND_TRUTH_ANNOTATION, indent=1) + "\n"
    )

    monkeypatch.setenv("CARUCA_V1_ROOT", str(root))
    return root


