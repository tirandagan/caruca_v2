# Syntax of mogrify (ImageMagick 6.9.12 Q16).
#
# Every option exists in a `-name` and a `+name` form; the `+` form usually resets a
# setting (and then takes no argument) or applies the operator differently. The two
# forms are distinct options, so both are listed. Options may be repeated, so the
# ones that take a value are ZERO_OR_MORE.
